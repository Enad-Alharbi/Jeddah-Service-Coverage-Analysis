PROMPT ===== 1. Row counts vs data/DATA_REPORT.md =====
WITH c AS (
  SELECT 'districts'          AS CHECK_NAME, (SELECT COUNT(*) FROM DISTRICTS) AS ACTUAL, 147 AS EXPECTED FROM DUAL UNION ALL
  SELECT 'districts non-residential', (SELECT COUNT(*) FROM DISTRICTS WHERE NON_RESIDENTIAL = 1), 4 FROM DUAL UNION ALL
  SELECT 'facilities school', (SELECT COUNT(*) FROM FACILITIES WHERE SERVICE_TYPE = 'school'), 215 FROM DUAL UNION ALL
  SELECT 'facilities health', (SELECT COUNT(*) FROM FACILITIES WHERE SERVICE_TYPE = 'health'), 122 FROM DUAL UNION ALL
  SELECT 'facilities park',   (SELECT COUNT(*) FROM FACILITIES WHERE SERVICE_TYPE = 'park'),   364 FROM DUAL UNION ALL
  SELECT 'facilities outside all districts', (SELECT COUNT(*) FROM FACILITIES WHERE DISTRICT_ID IS NULL), 12 FROM DUAL
)
SELECT CHECK_NAME, ACTUAL, EXPECTED, CASE WHEN ACTUAL = EXPECTED THEN 'OK' ELSE 'DIFF' END AS STATUS FROM c;

PROMPT ===== 2. Invalid geometries (expect 0 rows) =====
SELECT 'DISTRICTS' AS TBL, DISTRICT_CODE AS ID, SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(GEOM, 0.05) AS RESULT
FROM   DISTRICTS  WHERE SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(GEOM, 0.05) <> 'TRUE'
UNION ALL
SELECT 'FACILITIES', FACILITY_ID, SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(GEOM, 0.05)
FROM   FACILITIES WHERE SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(GEOM, 0.05) <> 'TRUE';

PROMPT ===== 3. District overlaps (expect 0 rows) =====
-- Neighbours should only TOUCH (share a border). Any interior overlap, containment or equality is a data error.
-- SDO_RELATE with a mask returns pairs whose topological relationship matches any listed relation.
SELECT a.NAME_AR AS NAME_A, b.NAME_AR AS NAME_B,
       SDO_GEOM.RELATE(a.GEOM, 'DETERMINE', b.GEOM, 0.05) AS RELATION,
       ROUND(SDO_GEOM.SDO_AREA(SDO_GEOM.SDO_INTERSECTION(a.GEOM, b.GEOM, 0.05), 0.05, 'unit=SQ_M'), 1) AS OVERLAP_M2
FROM   DISTRICTS a, DISTRICTS b
WHERE  a.ID < b.ID
AND    SDO_RELATE(a.GEOM, b.GEOM, 'mask=OVERLAPBDYINTERSECT+OVERLAPBDYDISJOINT+INSIDE+COVEREDBY+CONTAINS+COVERS+EQUAL') = 'TRUE';

PROMPT ===== 3b. Neighbour pairs that share a border (information) =====
SELECT COUNT(*) AS TOUCHING_PAIRS
FROM   DISTRICTS a, DISTRICTS b
WHERE  a.ID < b.ID
AND    SDO_RELATE(a.GEOM, b.GEOM, 'mask=TOUCH') = 'TRUE';

PROMPT ===== 4. Facilities outside every district (kept because within 1 km: edge effect) =====
-- SDO_WITHIN_DISTANCE (index-assisted) finds districts within 1.1 km; SDO_DISTANCE gives the exact geodesic meters.
SELECT f.FACILITY_ID, f.SERVICE_TYPE, NVL(f.NAME_AR, f.NAME_EN) AS NAME_AR,
       (SELECT ROUND(MIN(SDO_GEOM.SDO_DISTANCE(d.GEOM, f.GEOM, 0.05, 'unit=M')))
        FROM   DISTRICTS d
        WHERE  SDO_WITHIN_DISTANCE(d.GEOM, f.GEOM, 'distance=1100 unit=M') = 'TRUE') AS NEAREST_DISTRICT_M
FROM   FACILITIES f
WHERE  f.DISTRICT_ID IS NULL
ORDER  BY NEAREST_DISTRICT_M;

PROMPT ===== 5. Spatial metadata and index health =====
SELECT TABLE_NAME, COLUMN_NAME, SRID FROM USER_SDO_GEOM_METADATA ORDER BY TABLE_NAME, COLUMN_NAME;

COLUMN INDEX_NAME FORMAT A28
COLUMN PARAMETERS FORMAT A28
SELECT INDEX_NAME, TABLE_NAME, ITYP_NAME, DOMIDX_STATUS, DOMIDX_OPSTATUS, PARAMETERS
FROM   USER_INDEXES
WHERE  INDEX_TYPE = 'DOMAIN'
ORDER  BY TABLE_NAME;

PROMPT ===== 6. EXPLAIN PLAN: point-in-polygon spatial join (look for DOMAIN INDEX) =====
EXPLAIN PLAN SET STATEMENT_ID = 'SPATIAL_JOIN' FOR
SELECT d.ID, COUNT(*)
FROM   DISTRICTS d, FACILITIES f
WHERE  f.SERVICE_TYPE = 'school'
AND    SDO_RELATE(d.GEOM, f.GEOM, 'mask=CONTAINS+COVERS') = 'TRUE'
GROUP  BY d.ID;
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY(NULL, 'SPATIAL_JOIN', 'BASIC +PREDICATE'));

PROMPT ===== 6b. EXPLAIN PLAN: facilities within 800 m of one district (the coverage pre-filter) =====
EXPLAIN PLAN SET STATEMENT_ID = 'WITHIN_DIST' FOR
SELECT f.ID
FROM   FACILITIES f, DISTRICTS d
WHERE  d.DISTRICT_CODE = 'JED-20039328'
AND    f.SERVICE_TYPE = 'school'
AND    SDO_WITHIN_DISTANCE(f.GEOM, d.GEOM, 'distance=800 unit=M') = 'TRUE';
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY(NULL, 'WITHIN_DIST', 'BASIC +PREDICATE'));

PROMPT ===== 7. RECTIFY demo (not stored): a "bow-tie" polygon that crosses itself =====
-- All loaded data was already valid, so this shows what validation + rectification do on a broken shape.
COLUMN BEFORE FORMAT A20
COLUMN AFTER  FORMAT A10
SELECT SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(g, 0.05) AS BEFORE,
       SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(SDO_UTIL.RECTIFY_GEOMETRY(g, 0.05), 0.05) AS AFTER,
       SDO_UTIL.RECTIFY_GEOMETRY(g, 0.05).SDO_GTYPE AS GTYPE_AFTER
FROM (
  SELECT SDO_GEOMETRY(2003, 4326, NULL, SDO_ELEM_INFO_ARRAY(1, 1003, 1),
         SDO_ORDINATE_ARRAY(39.10, 21.50, 39.11, 21.51, 39.11, 21.50, 39.10, 21.51, 39.10, 21.50)) AS g
  FROM DUAL
);
